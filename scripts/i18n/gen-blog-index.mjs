/**
 * Blog index.ts'i blog/ klasorundeki tum *.json'lardan otomatik uretir.
 * Edge runtime fs okuyamaz -> build-time static import gerekiyor; bu script
 * tum makaleleri import edip ARTICLES array'e ekleyen index.ts'i yazar.
 * Calistir: node scripts/i18n/gen-blog-index.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BLOG_DIR = path.resolve(__dirname, "../../src/data/blog");

const files = fs
  .readdirSync(BLOG_DIR)
  .filter((f) => f.endsWith(".json"))
  .sort();

const ident = (f) => "a_" + f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_");

const header = `// AUTO-GENERATED by scripts/i18n/gen-blog-index.mjs — do not edit by hand.
// Edge runtime fs okuyamaz, bu yuzden build-time static import gerekiyor.
// Yeni blog JSON ekleyince: node scripts/i18n/gen-blog-index.mjs
//
// Importers: src/app/[locale]/blog/[slug]/page.tsx, sitemap.ts, blog/page.tsx, blog/rss.xml/route.ts
`;

const imports = files.map((f) => `import ${ident(f)} from "./${f}";`).join("\n");

const iface = `
export interface BlogArticle {
  slug: string;
  title: string;
  metaTitle: string;
  metaDescription: string;
  excerpt: string;
  content: string;
  category: string;
  tags: string[];
  targetKeyword: string;
  locale: string;
  publishedAt: string;
  seoScore: number;
  isAiGenerated?: boolean;
  /** Relative path under /public — e.g. "/images/blog/<slug>.jpg". */
  coverImage?: string;
  faq?: { question: string; answer: string }[];
}
`;

const arr =
  "\nexport const ARTICLES: BlogArticle[] = [\n" +
  files.map((f) => `  ${ident(f)} as BlogArticle,`).join("\n") +
  "\n];\n";

fs.writeFileSync(path.join(BLOG_DIR, "index.ts"), header + "\n" + imports + "\n" + iface + arr, "utf8");
console.log(`wrote index.ts with ${files.length} articles`);
