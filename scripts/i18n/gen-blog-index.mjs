/**
 * Blog manifest uretici. Makale JSON'lari public/blog/ icinde STATIK asset
 * (edge Worker bundle'a girmez — 3 MiB limit). Bu script metadata-only manifest
 * (content/faq HARIC) src/data/blog/index.ts'i uretir; tam icerik [slug]
 * sayfasinda runtime fetch ile /blog/<file> uzerinden alinir.
 * Calistir: node scripts/i18n/gen-blog-index.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PUBLIC_BLOG = path.resolve(__dirname, "../../public/blog");
const OUT = path.resolve(__dirname, "../../src/data/blog/index.ts");

const files = fs.readdirSync(PUBLIC_BLOG).filter((f) => f.endsWith(".json")).sort();

const metas = files.map((file) => {
  const a = JSON.parse(fs.readFileSync(path.join(PUBLIC_BLOG, file), "utf8"));
  return {
    file,
    slug: a.slug,
    title: a.title,
    metaTitle: a.metaTitle ?? a.title,
    metaDescription: a.metaDescription ?? "",
    excerpt: a.excerpt ?? "",
    category: a.category ?? "",
    tags: a.tags ?? [],
    targetKeyword: a.targetKeyword ?? "",
    locale: a.locale,
    publishedAt: a.publishedAt,
    seoScore: a.seoScore ?? 0,
    isAiGenerated: a.isAiGenerated ?? false,
    coverImage: a.coverImage,
  };
});

const out = `// AUTO-GENERATED by scripts/i18n/gen-blog-index.mjs — do not edit by hand.
// Makale icerikleri public/blog/*.json STATIK asset (edge Worker 3 MiB limiti icin
// bundle DISI). Burada sadece metadata manifest var; tam icerik [slug] sayfasinda
// /blog/<file> fetch ile alinir (bkz. blog/[slug]/page.tsx getArticle).
// Yeni JSON ekleyince: node scripts/i18n/gen-blog-index.mjs
//
// Importers: blog/page.tsx, blog/[slug]/page.tsx, sitemap.ts, blog/rss.xml/route.ts

/** Tam makale (icerik fetch ile gelir). */
export interface BlogArticle extends BlogArticleMeta {
  content: string;
  faq?: { question: string; answer: string }[];
}

/** Manifest metadata (content/faq HARIC) — bundle-safe. */
export interface BlogArticleMeta {
  /** public/blog altindaki dosya adi (runtime fetch icin). */
  file: string;
  slug: string;
  title: string;
  metaTitle: string;
  metaDescription: string;
  excerpt: string;
  category: string;
  tags: string[];
  targetKeyword: string;
  locale: string;
  publishedAt: string;
  seoScore: number;
  isAiGenerated?: boolean;
  coverImage?: string;
}

export const ARTICLES: BlogArticleMeta[] = ${JSON.stringify(metas, null, 2)};
`;

fs.writeFileSync(OUT, out, "utf8");
console.log(`wrote manifest with ${metas.length} articles (metadata-only)`);
